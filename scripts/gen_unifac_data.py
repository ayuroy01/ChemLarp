"""Regenerates src/unifac_data.inc, the original UNIFAC parameters (VLE), from the tables published by DDBST
(Dortmund Data Bank) as distributed with the `thermo` Python package (MIT licence).

Sources of the parameter values: Fredenslund, Jones & Prausnitz, AIChE J. 21 (1975) 1086; Hansen, Rasmussen,
Fredenslund, Schiller & Gmehling, Ind. Eng. Chem. Res. 30 (1991) 2352; Wittig, Lohmann & Gmehling,
Ind. Eng. Chem. Res. 42 (2003) 183; DDBST "Published UNIFAC parameters".

Usage: python scripts/gen_unifac_data.py > src/unifac_data.inc   (requires `pip install thermo`)
"""
import thermo
import thermo.unifac as U


def main():
    print("// Generated by scripts/gen_unifac_data.py from the DDBST-published original UNIFAC tables")
    print(f"// (thermo {thermo.__version__}). Do not edit by hand.")
    print("// {subgroup id, main group id, R_k, Q_k, name}")
    print("const UnifacSubgroup kUnifacSubgroups[] = {")
    for sid in sorted(U.UFSG):
        g = U.UFSG[sid]
        print(f'    {{{sid}, {g.main_group_id}, {g.R!r}, {g.Q!r}, "{g.group}"}},')
    print("};")
    print("// {main group m, main group n, a_mn in K}; a_mm = 0; a missing pair is not available")
    print("const UnifacInteraction kUnifacInteractions[] = {")
    for m in sorted(U.UFIP):
        for n in sorted(U.UFIP[m]):
            print(f"    {{{m}, {n}, {U.UFIP[m][n]!r}}},")
    print("};")


if __name__ == "__main__":
    main()

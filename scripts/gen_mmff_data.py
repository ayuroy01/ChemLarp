#!/usr/bin/env python3
"""Generates src/mmff_data.inc from the MMFF94 parameter files.

The tables are Halgren's MMFF94 / MMFF94s parameter files (MMFFDEF, MMFFPROP, MMFFPBCI, MMFFCHG, MMFFBOND,
MMFFBNDK, MMFFANG, MMFFSTBN, MMFFDFSB, MMFFOOP, MMFFTOR, MMFFVDW; Halgren, J. Comput. Chem. 17 (1996)
490-641, supplementary material; Merck & Co.). The copies used are the text blocks embedded verbatim in
RDKit's Code/ForceField/MMFF/Params.cpp (BSD licence), from which only the data are read:

  python3 scripts/gen_mmff_data.py path/to/Params.cpp > src/mmff_data.inc

The Herschbach-Laurie and covalent-radius / electronegativity tables used by the empirical bond rule are
read from the same file.
"""
import re
import sys


def blocks(path):
    src = open(path, encoding="utf-8").read()
    out = {}
    for m in re.finditer(r"const std::string (defaultMMFF\w+)(\[\])?\s*=\s*\{?((?:\s*\"(?:[^\"\\]|\\.)*\"\s*,?)+)\s*\}?\s*;", src):
        parts = re.findall(r'"((?:[^"\\]|\\.)*)"', m.group(3))
        out[m.group(1)] = "".join(parts).encode().decode("unicode_escape")
    return out


def rows(text):
    for line in text.split("\n"):
        if not line.strip() or line.startswith("*") or line.startswith("$") or line.strip() == "EOS":
            continue
        yield line.split()


def main():
    b = blocks(sys.argv[1])
    o = []
    o.append("// Generated by scripts/gen_mmff_data.py from Halgren's MMFF94 parameter files")
    o.append("// (Copyright (c) Merck and Co., Inc., 1994, 1995, 1996; published as supplementary material to")
    o.append("// J. Comput. Chem. 17 (1996) 490-641). Do not edit by hand.")

    o.append("// MMFFPROP: atomic number, crd, val, pilp, mltb, arom, lin, sbmb (index = type).")
    prop = {int(r[0]): r[1:9] for r in rows(b["defaultMMFFProp"])}
    o.append("static const MmffProp kMmffProp[100] = {")
    for t in range(100):
        p = prop.get(t)
        o.append("    {" + (", ".join(p) if p else "0, 0, 0, 0, 0, 0, 0, 0") + "},  // " + str(t))
    o.append("};")

    o.append("// MMFFDEF: equivalence levels 1-4 (index = type).")
    defs = {}
    for r in rows(b["defaultMMFFDef"]):
        defs[int(r[1])] = (r[0], [int(x) for x in r[2:6]])
    o.append("static const MmffDef kMmffDef[100] = {")
    for t in range(100):
        sym, lv = defs.get(t, ("", [0, 0, 0, 0]))
        o.append(f'    {{"{sym}", {{{", ".join(map(str, lv))}}}}},')
    o.append("};")

    o.append("// MMFFPBCI: partial bond charge increment, formal-charge adjustment (index = type).")
    pb = {int(r[1]): (r[2], r[3]) for r in rows(b["defaultMMFFPBCI"])}
    o.append("static const MmffPbci kMmffPbci[100] = {")
    for t in range(100):
        p = pb.get(t)
        o.append("    {" + (f"{p[0]}, {p[1]}, true" if p else "0.0, 0.0, false") + "},")
    o.append("};")

    def table(name, key_n, val_n, cname, ctype):
        o.append(f"static const {ctype} {cname}[] = {{")
        n = 0
        for r in rows(b[name]):
            keys = r[:key_n]
            vals = r[key_n:key_n + val_n]
            o.append("    {" + ", ".join(keys + vals) + "},")
            n += 1
        o.append("};")
        return n

    table("defaultMMFFChg", 3, 1, "kMmffChg", "MmffChg")
    table("defaultMMFFBond", 3, 2, "kMmffBond", "MmffBond")
    table("defaultMMFFBndk", 2, 2, "kMmffBndk", "MmffBndk")
    table("defaultMMFFHerschbachLaurie", 2, 3, "kMmffHL", "MmffHL")
    table("defaultMMFFCovRadPauEle", 1, 2, "kMmffCovRad", "MmffCovRad")
    o.append("static const MmffAngle kMmffAngle[] = {")
    for r in rows(b["defaultMMFFAngleData"]):
        o.append("    {" + ", ".join(r[:6]) + "},")
    o.append("};")
    table("defaultMMFFStbn", 4, 2, "kMmffStbn", "MmffStbn")
    table("defaultMMFFDfsb", 3, 2, "kMmffDfsb", "MmffDfsb")
    table("defaultMMFFOop", 4, 1, "kMmffOop", "MmffOop")
    table("defaultMMFFsOop", 4, 1, "kMmffsOop", "MmffOop")
    table("defaultMMFFTor", 5, 3, "kMmffTor", "MmffTor")
    table("defaultMMFFsTor", 5, 3, "kMmffsTor", "MmffTor")

    vdw = list(rows(b["defaultMMFFVdW"]))
    head = vdw[0]
    o.append(f"static const double kMmffVdwPower = {head[0]}, kMmffVdwB = {head[1]}, kMmffVdwBeta = {head[2]},")
    o.append(f"                    kMmffDARAD = {head[3]}, kMmffDAEPS = {head[4]};")
    o.append("static const MmffVdw kMmffVdw[] = {")
    for r in vdw[1:]:
        da = {"-": 0, "D": 1, "A": 2}[r[5]]
        o.append(f"    {{{r[0]}, {r[1]}, {r[2]}, {r[3]}, {r[4]}, {da}}},")
    o.append("};")
    print("\n".join(o))


if __name__ == "__main__":
    main()

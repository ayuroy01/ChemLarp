"""Regenerates src/antoine_data.inc, Antoine vapour-pressure coefficients from Poling, Prausnitz &
O'Connell, The Properties of Gases and Liquids, 5th ed. (McGraw-Hill 2001), as tabulated in the `chemicals`
Python package (MIT licence): log10(P/Pa) = A - B/(T/K + C), valid for Tmin <= T <= Tmax.
Compounds are keyed by SMILES (resolved from CAS numbers with `chemicals`).

Usage: python scripts/gen_antoine_data.py > src/antoine_data.inc   (requires `pip install chemicals`)
"""
import chemicals
import chemicals.identifiers as I
import chemicals.vapor_pressure as V


def main():
    df = V.Psat_data_AntoinePoling
    print("// Generated by scripts/gen_antoine_data.py: Antoine coefficients of Poling, Prausnitz & O'Connell,")
    print(f"// The Properties of Gases and Liquids, 5th ed. (chemicals {chemicals.__version__}). Do not edit by hand.")
    print("// {SMILES, name, A, B (K), C (K), Tmin (K), Tmax (K)}: log10(P/Pa) = A - B/(T + C)")
    print("const AntoineRow kAntoine[] = {")
    for cas, row in df.iterrows():
        try:
            meta = I.search_chemical(cas)
        except Exception:
            continue
        smiles = getattr(meta, "smiles", None)
        if not smiles:
            continue
        name = str(row["Chemical"]).strip().replace('"', "'")
        smiles = smiles.replace("\\", "\\\\")  # C string literal: escape the trans/cis bond marks
        print(f'    {{"{smiles}", "{name}", {row["A"]!r}, {row["B"]!r}, {row["C"]!r}, {row["Tmin"]!r}, {row["Tmax"]!r}}},')
    print("};")


if __name__ == "__main__":
    main()

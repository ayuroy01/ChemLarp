"""Regenerates src/transport_data.inc, transport-property correlations for the compounds of the
pure-component table (src/property_data.inc), from published compilations as distributed with the
`chemicals` Python package (MIT licence):

  L liquid viscosity (Pa s)          Perry's Chemical Engineers' Handbook, 8th ed., Table 2-313 (DIPPR eq. 101:
                                     exp(C1 + C2/T + C3 ln T + C4 T^C5))
  G vapour viscosity, low P (Pa s)   Perry Table 2-312 (DIPPR eq. 102: C1 T^C2 / (1 + C3/T + C4/T^2))
  l liquid thermal cond. (W/m/K)     Perry Table 2-315 (DIPPR eq. 100: C1 + C2 T + C3 T^2 + C4 T^3 + C5 T^4)
  g vapour thermal cond., low P      Perry Table 2-314 (DIPPR eq. 102)
  C liquid heat capacity (J/mol/K)   Perry Table 2-153 (DIPPR eq. 100; tabulated per kmol, converted here);
                                     a row that misses both Poling's and CRC's Cp(298.15 K) by more than 5% is dropped
  V saturated liquid density         VDI Heat Atlas (2010), PPDS equation: rho = rho_c + a tau^0.35 + b tau^(2/3)
                                     + c tau + d tau^(4/3), tau = 1 - T/Tc (stored: rho_c, a, b, c, d, Tc, M)
  s surface tension (N/m)            Mulero & Cachadina, J. Phys. Chem. Ref. Data 41 (2012) 043105:
                                     sum_i s_i (1 - T/Tc)^n_i; else Jasper, J. Phys. Chem. Ref. Data 1 (1972)
                                     841, as in Lange's Handbook: (a - b (T - 273.15)) mN/m

Apart from the liquid density, the VDI Heat Atlas (PPDS) correlations are deliberately not used here: they are
the independent reference for validation (Zabransky et al.'s evaluated liquid heat capacities likewise). The
liquid density uses VDI because Perry's DIPPR-105 table (the validation reference for it) has no water. Usage: python scripts/gen_transport_data.py > src/transport_data.inc
"""
import math
import os
import re
import sys

import chemicals
import pandas as pd

D = os.path.dirname(chemicals.__file__)
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def table(rel):
    df = pd.read_csv(os.path.join(D, rel), sep="\t", index_col=0)
    return df[~df.index.duplicated(keep="first")]


def compounds():
    """(SMILES as written in the C source, CAS, Poling liquid Cp at 298.15 K) from the property table."""
    out = []
    for line in open(os.path.join(ROOT, "src", "property_data.inc")):
        m = re.match(r'\s*\{"((?:[^"\\]|\\.)*)", "[^"]*", "([^"]*)", (.*)\},', line)
        if m:
            fields = m.group(3).split(", ")
            cpl = float(fields[16]) if fields[16] != "NAN" else math.nan
            out.append((m.group(1), m.group(2), cpl))
    return out


def num(df, cas, col):
    try:
        v = float(df.at[cas, col])
    except (KeyError, TypeError, ValueError):
        return math.nan
    return v if math.isfinite(v) else math.nan


def f(v):
    v = float(v)
    return repr(v) if math.isfinite(v) else "0.0"


def main():
    perry = {
        "L": ("1", table("Viscosity/Table 2-313 Viscosity of Inorganic and Organic Liquids.tsv"), 5),
        "G": ("2", table("Viscosity/Table 2-312 Vapor Viscosity of Inorganic and Organic Substances.tsv"), 4),
        "l": ("0", table("Thermal Conductivity/Table 2-315 Thermal Conductivity of Inorganic and Organic Liquids.tsv"), 5),
        "g": ("2", table("Thermal Conductivity/Table 2-314 Vapor Thermal Conductivity of Inorganic and Organic Substances.tsv"), 4),
    }
    cpl = table("Heat Capacity/Perry_Table_2-153_DIPPR_100.tsv")
    crc_thermo = table("Heat Capacity/CRC Standard Thermodynamic Properties of Chemical Substances.tsv")
    vdi_rho = table("Density/VDI PPDS Density of Saturated Liquids.tsv")
    mulero = table("Interface/MuleroCachadinaParameters.tsv")
    jasper = table("Interface/Jasper-Lange.tsv")
    print("// Generated by scripts/gen_transport_data.py from published compilations (chemicals "
          f"{chemicals.__version__}); see the script for sources and equations. Do not edit by hand.")
    print("// {SMILES, property, equation, c[0..6], Tmin K, Tmax K}")
    print("const TransportRow kTransport[] = {")
    for smiles, cas, cpl298 in compounds():
        for prop, (eq, df, n) in perry.items():
            if cas not in df.index:
                continue
            r = df.loc[cas]
            c = [f(r[f"C{i + 1}"]) for i in range(n)] + ["0.0"] * (7 - n)
            print(f'    {{"{smiles}", \'{prop}\', \'{eq}\', {{{", ".join(c)}}}, {f(r.Tmin)}, {f(r.Tmax)}}},')
        if cas in cpl.index:
            r = cpl.loc[cas]
            # Consistency check: inside its range, the Perry polynomial must reproduce at least one published
            # liquid Cp(298.15 K) (Poling, CRC) within 5%; a row that agrees with neither is dropped.
            k = [float(r[x]) / 1000.0 for x in "ABCDE"]
            cp298 = sum(ki * 298.15 ** i for i, ki in enumerate(k))
            refs = [v for v in (cpl298, num(crc_thermo, cas, "Cpl")) if not math.isnan(v)]
            if r.Tmin <= 298.15 <= r.Tmax and refs and all(abs(cp298 / v - 1) > 0.05 for v in refs):
                print(f"# {cas}: Perry liquid Cp {cp298:.1f} at 298 K, references {refs}; dropped", file=sys.stderr)
                continue
            c = [f(float(r[k]) / 1000.0) for k in "ABCDE"] + ["0.0"] * 2
            print(f'    {{"{smiles}", \'C\', \'0\', {{{", ".join(c)}}}, {f(r.Tmin)}, {f(r.Tmax)}}},')
        if cas in vdi_rho.index:
            r = vdi_rho.loc[cas]
            c = [f(r[k]) for k in ("rhoc", "A", "B", "C", "D", "Tc", "MW")]
            print(f'    {{"{smiles}", \'V\', \'P\', {{{", ".join(c)}}}, 0.0, {f(r.Tc)}}},')
        if cas in mulero.index:
            r = mulero.loc[cas]
            c = [f(r[k]) for k in ("sigma0", "n0", "sigma1", "n1", "sigma2", "n2", "Tc")]
            print(f'    {{"{smiles}", \'s\', \'M\', {{{", ".join(c)}}}, {f(r.Tmin)}, {f(r.Tmax)}}},')
        elif cas in jasper.index:
            r = jasper.loc[cas]
            c = [f(r.a), f(r.b)] + ["0.0"] * 5
            print(f'    {{"{smiles}", \'s\', \'J\', {{{", ".join(c)}}}, {f(r.Tmin)}, {f(r.Tmax)}}},')
    print("};")


if __name__ == "__main__":
    main()

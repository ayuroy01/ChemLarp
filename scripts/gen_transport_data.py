"""Regenerates src/transport_data.inc, transport-property correlations for the compounds of the
pure-component table (src/property_data.inc), from published compilations as distributed with the
`chemicals` Python package (MIT licence):

  L liquid viscosity (Pa s)          Perry's Chemical Engineers' Handbook, 8th ed., Table 2-313 (DIPPR eq. 101:
                                     exp(C1 + C2/T + C3 ln T + C4 T^C5))
  G vapour viscosity, low P (Pa s)   Perry Table 2-312 (DIPPR eq. 102: C1 T^C2 / (1 + C3/T + C4/T^2))
  l liquid thermal cond. (W/m/K)     Perry Table 2-315 (DIPPR eq. 100: C1 + C2 T + C3 T^2 + C4 T^3 + C5 T^4)
  g vapour thermal cond., low P      Perry Table 2-314 (DIPPR eq. 102)
  s surface tension (N/m)            Mulero & Cachadina, J. Phys. Chem. Ref. Data 41 (2012) 043105:
                                     sum_i s_i (1 - T/Tc)^n_i; else Jasper, J. Phys. Chem. Ref. Data 1 (1972)
                                     841, as in Lange's Handbook: (a - b (T - 273.15)) mN/m

The VDI Heat Atlas (PPDS) correlations are deliberately not used here: they are the independent reference
for validation. Usage: python scripts/gen_transport_data.py > src/transport_data.inc
"""
import math
import os
import re

import chemicals
import pandas as pd

D = os.path.dirname(chemicals.__file__)
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def table(rel):
    df = pd.read_csv(os.path.join(D, rel), sep="\t", index_col=0)
    return df[~df.index.duplicated(keep="first")]


def compounds():
    """(SMILES as written in the C source, CAS) from the generated property table."""
    out = []
    for line in open(os.path.join(ROOT, "src", "property_data.inc")):
        m = re.match(r'\s*\{"((?:[^"\\]|\\.)*)", "[^"]*", "([^"]*)"', line)
        if m:
            out.append((m.group(1), m.group(2)))
    return out


def f(v):
    v = float(v)
    return repr(v) if math.isfinite(v) else "0.0"


def main():
    perry = {
        "L": ("1", table("Viscosity/Table 2-313 Viscosity of Inorganic and Organic Liquids.tsv"), 5),
        "G": ("2", table("Viscosity/Table 2-312 Vapor Viscosity of Inorganic and Organic Substances.tsv"), 4),
        "l": ("0", table("Thermal Conductivity/Table 2-315 Thermal Conductivity of Inorganic and Organic Liquids.tsv"), 5),
        "g": ("2", table("Thermal Conductivity/Table 2-314 Vapor Thermal Conductivity of Inorganic and Organic Substances.tsv"), 4),
    }
    mulero = table("Interface/MuleroCachadinaParameters.tsv")
    jasper = table("Interface/Jasper-Lange.tsv")
    print("// Generated by scripts/gen_transport_data.py from published compilations (chemicals "
          f"{chemicals.__version__}); see the script for sources and equations. Do not edit by hand.")
    print("// {SMILES, property, equation, c[0..6], Tmin K, Tmax K}")
    print("const TransportRow kTransport[] = {")
    for smiles, cas in compounds():
        for prop, (eq, df, n) in perry.items():
            if cas not in df.index:
                continue
            r = df.loc[cas]
            c = [f(r[f"C{i + 1}"]) for i in range(n)] + ["0.0"] * (7 - n)
            print(f'    {{"{smiles}", \'{prop}\', \'{eq}\', {{{", ".join(c)}}}, {f(r.Tmin)}, {f(r.Tmax)}}},')
        if cas in mulero.index:
            r = mulero.loc[cas]
            c = [f(r[k]) for k in ("sigma0", "n0", "sigma1", "n1", "sigma2", "n2", "Tc")]
            print(f'    {{"{smiles}", \'s\', \'M\', {{{", ".join(c)}}}, {f(r.Tmin)}, {f(r.Tmax)}}},')
        elif cas in jasper.index:
            r = jasper.loc[cas]
            c = [f(r.a), f(r.b)] + ["0.0"] * 5
            print(f'    {{"{smiles}", \'s\', \'J\', {{{", ".join(c)}}}, {f(r.Tmin)}, {f(r.Tmax)}}},')
    print("};")


if __name__ == "__main__":
    main()
